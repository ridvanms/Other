import type { AgeRating, ContentFlags, Ending, Genre, Movie } from '../types';

/**
 * Hand-curated catalog.
 *
 * Profiles are scored 0–10 in this order:
 *   fear, tension, mindbend, humor, romance, action, sadness, darkness, wonder, pace
 *
 * Endings and content flags are recorded so the app can filter on them
 * without ever showing a spoiler.
 */

type Flag = keyof ContentFlags;
type ProfileTuple = [number, number, number, number, number, number, number, number, number, number];

interface RawMovie {
  id: string;
  title: string;
  aliases?: string[];
  year: number;
  runtime: number;
  director: string;
  country: string;
  language: string;
  genres: Genre[];
  tags: string[];
  profile: ProfileTuple;
  ending: Ending;
  flags?: Flag[];
  age: AgeRating;
  palette: [string, string, string];
  blurb: string;
}

function movie(raw: RawMovie): Movie {
  const [fear, tension, mindbend, humor, romance, action, sadness, darkness, wonder, pace] = raw.profile;
  const flags = new Set(raw.flags ?? []);
  return {
    id: raw.id,
    title: raw.title,
    ...(raw.aliases ? { aliases: raw.aliases } : {}),
    year: raw.year,
    runtime: raw.runtime,
    director: raw.director,
    country: raw.country,
    language: raw.language,
    genres: raw.genres,
    tags: raw.tags,
    profile: { fear, tension, mindbend, humor, romance, action, sadness, darkness, wonder, pace },
    ending: raw.ending,
    flags: { gore: flags.has('gore'), jumpscares: flags.has('jumpscares'), animalDeath: flags.has('animalDeath') },
    age: raw.age,
    blurb: raw.blurb,
    palette: raw.palette,
  };
}

